export const findCase = (page: string) => {
  const year = YEARS.find(y => y.cases.some(c => c.page === page));
  if (!year) throw new Error(`YEARS に ${page} がない`);
  const i = year.cases.findIndex(c => c.page === page);
  return { year, c: year.cases[i], prev: year.cases[i - 1], next: year.cases[i + 1] };
};
